-- Products table for Molten Stories.
-- Run in the Supabase dashboard: SQL Editor -> New query -> paste -> Run.

create table if not exists public.products (
  id          bigint generated by default as identity primary key,
  name        text not null,
  category    text not null,
  categories  text[] not null default '{}',   -- extra collections; empty = use `category` only
  price       numeric(10,2) not null check (price >= 0),
  old_price   numeric(10,2) check (old_price >= 0),  -- struck-through price (was `old`)
  color       text,                            -- fallback colour for the illustrated candle
  images      text[] not null default '{}',    -- first is the main photo
  description text,
  disabled    boolean not null default false,  -- hidden from the storefront
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create or replace function public.set_updated_at() returns trigger as $$
begin
  new.updated_at = now();
  return new;
end;
$$ language plpgsql;

drop trigger if exists products_updated_at on public.products;
create trigger products_updated_at before update on public.products
  for each row execute function public.set_updated_at();

-- Row-level security: public can read enabled products; only signed-in admins can do anything else.
alter table public.products enable row level security;

drop policy if exists "Public reads enabled products" on public.products;
create policy "Public reads enabled products" on public.products
  for select using (disabled = false);

drop policy if exists "Admins read all products" on public.products;
create policy "Admins read all products" on public.products
  for select to authenticated using (true);

drop policy if exists "Admins write products" on public.products;
create policy "Admins write products" on public.products
  for all to authenticated using (true) with check (true);

-- NOTE: any signed-in user counts as admin. Keep public sign-ups DISABLED in
-- Supabase (Authentication -> Providers -> Email -> turn off "Allow new users to sign up")
-- and create your admin user manually.

-- Storage bucket for product photos (public read, admin write).
insert into storage.buckets (id, name, public)
values ('product-images', 'product-images', true)
on conflict (id) do nothing;

drop policy if exists "Public reads product images" on storage.objects;
create policy "Public reads product images" on storage.objects
  for select using (bucket_id = 'product-images');

drop policy if exists "Admins manage product images" on storage.objects;
create policy "Admins manage product images" on storage.objects
  for all to authenticated
  using (bucket_id = 'product-images') with check (bucket_id = 'product-images');

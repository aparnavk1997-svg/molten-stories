-- Customer reviews, with admin moderation.
-- Run in the Supabase dashboard: SQL Editor -> New query -> paste -> Run.
-- Requires 0001 and 0002 (uses set_updated_at() and is_admin()).

create table if not exists public.reviews (
  id           bigint generated by default as identity primary key,
  user_id      uuid references auth.users (id) on delete set null,   -- null when a guest wrote it
  name         text not null check (char_length(trim(name)) between 1 and 60),
  city         text not null default '' check (char_length(city) <= 60),
  product_id   bigint references public.products (id) on delete set null,
  product_name text not null default '' check (char_length(product_name) <= 120),  -- kept even if the product is later removed
  rating       smallint not null check (rating between 1 and 5),
  body         text not null check (char_length(trim(body)) between 10 and 400),
  status       text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  sort_order   integer not null default 999,   -- position on the site: 1, 2, 3 ... (999 = last)
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);

-- Safe to re-run: adds the column if this file was already run before it existed.
alter table public.reviews add column if not exists sort_order integer not null default 999;

create index if not exists reviews_status_idx  on public.reviews (status, created_at desc);
create index if not exists reviews_product_idx on public.reviews (product_id) where status = 'approved';
create index if not exists reviews_user_idx    on public.reviews (user_id);

drop trigger if exists reviews_updated_at on public.reviews;
create trigger reviews_updated_at before update on public.reviews
  for each row execute function public.set_updated_at();

alter table public.reviews enable row level security;

-- Status meanings: pending = waiting for the admin, approved = shown on the site ("enabled"), rejected = hidden ("disabled").

-- Anyone (guest or signed in) can submit a review, but only as "pending" and only as themselves.
drop policy if exists "Anyone can submit a review" on public.reviews;
create policy "Anyone can submit a review" on public.reviews
  for insert to anon, authenticated
  with check (status = 'pending' and sort_order = 999 and (user_id is null or user_id = auth.uid()));

-- The public sees approved reviews only.
drop policy if exists "Public reads approved reviews" on public.reviews;
create policy "Public reads approved reviews" on public.reviews
  for select to anon, authenticated using (status = 'approved');

-- Signed-in customers can also see their own reviews while they wait for approval.
drop policy if exists "Customers read own reviews" on public.reviews;
create policy "Customers read own reviews" on public.reviews
  for select to authenticated using (user_id = auth.uid());

-- Admins approve, reject, edit and delete.
drop policy if exists "Admins manage reviews" on public.reviews;
create policy "Admins manage reviews" on public.reviews
  for all to authenticated using (public.is_admin()) with check (public.is_admin());

-- Visitors who aren't signed in never need to see who wrote a review (user_id), so don't expose it.
-- NOTE: because of this, always list columns explicitly when reading as a visitor (no select('*')).
revoke select on public.reviews from anon;
grant select (id, name, city, product_id, product_name, rating, body, status, sort_order, created_at) on public.reviews to anon;

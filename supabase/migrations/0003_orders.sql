-- Orders created by the admin, with a public "track by order ID" lookup.
-- Run in the Supabase dashboard: SQL Editor -> New query -> paste -> Run.
-- Requires 0001 and 0002 to have been run first.

-- Random, hard-to-guess order IDs such as ORD-3F9AC-21B7E (40 bits of randomness).
create or replace function public.new_order_code() returns text
language plpgsql set search_path = ''
as $$
declare
  v_code text;
  v_hex  text;
begin
  loop
    v_hex := upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 10));
    v_code := 'ORD-' || substr(v_hex, 1, 5) || '-' || substr(v_hex, 6, 5);
    exit when not exists (select 1 from public.orders o where o.code = v_code);
  end loop;
  return v_code;
end;
$$;

create table if not exists public.orders (
  id             bigint generated by default as identity primary key,
  code           text not null unique default 'pending',
  user_id        uuid references auth.users (id) on delete set null,  -- null for guests
  username       text not null,                                       -- 'GUEST' or the customer's username
  customer_name  text not null,
  phone          text not null check (phone ~ '^[0-9]{10}$'),
  street         text not null,
  city           text not null,
  state          text not null,
  pin            text not null check (pin ~ '^[0-9]{6}$'),
  items          jsonb not null check (jsonb_typeof(items) = 'array' and jsonb_array_length(items) > 0),
  subtotal       numeric(10,2) not null check (subtotal >= 0),
  delivery_fee   numeric(10,2) not null default 0 check (delivery_fee >= 0),
  total          numeric(10,2) not null check (total >= 0),
  notes          text not null default '',
  status         text not null default 'confirmed'
                 check (status in ('confirmed', 'packed', 'shipped', 'delivered', 'cancelled')),
  status_log     jsonb not null default '[]',
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);

-- Give every new order its random code (the column default is only a placeholder for the NOT NULL).
create or replace function public.orders_before_write() returns trigger
language plpgsql set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    new.code := public.new_order_code();
  else
    new.code := old.code;  -- the code never changes
  end if;
  -- Append to the status history whenever the status is set or changes.
  if tg_op = 'INSERT' or new.status is distinct from old.status then
    new.status_log := coalesce(new.status_log, '[]'::jsonb)
      || jsonb_build_array(jsonb_build_object('status', new.status, 'at', now()));
  end if;
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists orders_before_write on public.orders;
create trigger orders_before_write before insert or update on public.orders
  for each row execute function public.orders_before_write();

create index if not exists orders_user_id_idx on public.orders (user_id, created_at desc);

-- Row-level security: admins manage everything, customers can read only their own orders.
alter table public.orders enable row level security;

drop policy if exists "Admins manage orders" on public.orders;
create policy "Admins manage orders" on public.orders
  for all to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "Customers read own orders" on public.orders;
create policy "Customers read own orders" on public.orders
  for select to authenticated using (user_id = auth.uid());

-- Admins need to look up a customer's saved address by username when creating an order.
drop policy if exists "Admins read profiles" on public.profiles;
create policy "Admins read profiles" on public.profiles
  for select to authenticated using (public.is_admin());

-- Public tracking: anyone with the order ID sees status + items, but never the address or phone.
create or replace function public.track_order(p_code text) returns jsonb
language sql stable security definer set search_path = ''
as $$
  select jsonb_build_object(
    'code', o.code,
    'status', o.status,
    'status_log', o.status_log,
    'created_at', o.created_at,
    'total', o.total,
    'items', (
      select coalesce(jsonb_agg(jsonb_build_object('name', i ->> 'name', 'qty', i -> 'qty')), '[]'::jsonb)
      from jsonb_array_elements(o.items) i
    )
  )
  from public.orders o
  where o.code = upper(trim(p_code));
$$;

grant execute on function public.track_order(text) to anon, authenticated;
